import time
import logging
from datetime import datetime
from threading import Event, Thread
from typing import Type

from tokemfx.data    import DataHandler
from tokemfx.broker  import Broker
from tokemfx.strategy import BaseStrategy

logger = logging.getLogger(__name__)

class Executor:
    """
    Live/paper trading execution loop.
    """
    def __init__(
        self,
        broker: Broker,
        data_handler: DataHandler,
        strategy_cls: Type[BaseStrategy],
        strategy_params: dict,
        instrument: str,
        granularity: str,
        cash: float = 10_000,
        poll_interval: float = 60.0,
        paper: bool = True
    ):
        self.broker         = broker
        self.dh             = data_handler
        self.strategy_cls   = strategy_cls
        self.strategy_params= strategy_params
        self.instrument     = instrument
        self.granularity    = granularity
        self.cash           = cash
        self.poll_interval  = poll_interval
        self.paper          = paper

        # Backtrader‐style strategy instance for live operation
        self._cerebro = None
        self._strategy = None

        # Used to stop the loop cleanly
        self._stop_event = Event()

    def _initialize(self):
        # 1) Seed with historical data to prime indicators
        df = self.dh.get_historical(
            self.instrument,
            self.granularity,
            start=datetime.utcnow() - self._lookback_timedelta(),
            end=datetime.utcnow()
        )
        # 2) Build a minimal Cerebro + strategy node
        import backtrader as bt
        self._cerebro = bt.Cerebro()
        self._cerebro.broker.setcash(self.cash)
        self._cerebro.broker.setcommission(commission=0.0002)
        self._cerebro.broker.set_slippage_perc(0.0001)
        self._cerebro.addstrategy(self.strategy_cls, **self.strategy_params)
        data_feed = bt.feeds.PandasData(dataname=df)
        self._cerebro.adddata(data_feed)
        # grab the strategy instance
        self._strategy = self._cerebro.run()[0]
        logger.info("Executor initialized, strategy primed.")

    def _lookback_timedelta(self):
        # choose something like 100 × granularity period
        unit = self.granularity[-1]
        val  = int(self.granularity[:-1])
        mapping = {"M": "minutes", "H": "hours", "D": "days"}
        return {mapping[unit]: val * 100}

    def start(self):
        self._initialize()
        Thread(target=self._loop, daemon=True).start()
        logger.info("Executor started.")

    def _loop(self):
        while not self._stop_event.is_set():
            try:
                # 1) fetch the latest bar
                df = self.dh.get_latest(self.instrument, self.granularity, count=1)
                bar = df.iloc[-1]

                # 2) feed into strategy
                # Backtrader doesn’t do “tick by tick” easily –
                # you can call strategy.next() manually:
                self._strategy.data.lines.open[0]  = bar.open
                self._strategy.data.lines.high[0]  = bar.high
                self._strategy.data.lines.low[0]   = bar.low
                self._strategy.data.lines.close[0] = bar.close
                self._strategy.data.lines.volume[0]= bar.volume
                self._strategy.next()

                # 3) check for orders generated by strategy
                for order in list(self._strategy.broker.orders):
                    if order.status in [order.Completed]:
                        action = "BUY" if order.size>0 else "SELL"
                        logger.info(f"Executed {action} {abs(order.size)} @ {order.executed.price}")
                        # optionally notify here

                # 4) wait until next bar
                time.sleep(self.poll_interval)

            except Exception as e:
                logger.error(f"Executor loop error: {e}", exc_info=True)
                time.sleep(5)  # brief backoff

    def stop(self):
        self._stop_event.set()
        logger.info("Executor stopping…")
